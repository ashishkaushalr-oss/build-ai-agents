"""Inline the shared CSS/JS and the course URLs into every page in src/.

Usage
  python -I build.py [page-name ...]
      -> dist/<name>.html        the artifact bodies published to claude.ai (links point at the Claude artifacts)
      -> dist/preview/<name>.html the same, wrapped in the skeleton the platform adds, for local viewing
  python -I build.py --site [dir] [--doc-url URL] [page-name ...]
      -> a static site with relative links between pages, hub.html written as index.html (default dir: docs/).
         Serve it from GitHub Pages or any web host. --doc-url sets where "Course doc" links go.
"""
import hashlib, json, os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC, DIST, SHARED, ASSETS = os.path.join(HERE, 'src'), os.path.join(HERE, 'dist'), os.path.join(HERE, 'shared'), os.path.join(HERE, 'assets')
SKELETON = ('<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
            '<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style></head><body>')

# The static site is also an installable web app. These head tags, the manifest, the icons and the service worker
# exist only in the --site build; the Claude artifacts get none of it.
SITE_HEAD = ('<link rel="manifest" href="manifest.webmanifest"><link rel="icon" href="icon.svg" type="image/svg+xml">'
             '<link rel="icon" href="favicon-32.png" sizes="32x32" type="image/png"><link rel="apple-touch-icon" href="apple-touch-icon.png">'
             '<meta name="theme-color" content="#F4F6FB" media="(prefers-color-scheme: light)"><meta name="theme-color" content="#0B1020" media="(prefers-color-scheme: dark)">'
             '<meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-capable" content="yes">'
             '<meta name="apple-mobile-web-app-status-bar-style" content="default"><meta name="apple-mobile-web-app-title" content="AI Agents">')
ICON_FILES = ['icon.svg', 'icon-192.png', 'icon-512.png', 'icon-maskable-192.png', 'icon-maskable-512.png', 'apple-touch-icon.png', 'favicon-32.png']
MANIFEST = {
    'name': 'Build Your Own AI Agents', 'short_name': 'AI Agents',
    'description': 'A ten-week, no-code course on building AI agents with Claude and n8n.',
    'id': './', 'start_url': './index.html', 'scope': './', 'display': 'standalone', 'lang': 'en',
    'background_color': '#09090B', 'theme_color': '#F4F6FB',
    'icons': [
        {'src': 'icon-192.png', 'sizes': '192x192', 'type': 'image/png', 'purpose': 'any'},
        {'src': 'icon-512.png', 'sizes': '512x512', 'type': 'image/png', 'purpose': 'any'},
        {'src': 'icon-maskable-192.png', 'sizes': '192x192', 'type': 'image/png', 'purpose': 'maskable'},
        {'src': 'icon-maskable-512.png', 'sizes': '512x512', 'type': 'image/png', 'purpose': 'maskable'},
    ],
}
# Service worker: every page and icon is stored on the first visit, so the course opens offline. Pages are fetched
# fresh when online (falling back to the stored copy), fonts and the Firebase library are kept once fetched, and
# everything else (Firestore, Google sign-in) goes straight to the network. The version changes with the content.
SW_TEMPLATE = r"""/* Build Your Own AI Agents: offline support. Generated by build.py; do not edit by hand. */
var VERSION = '@VERSION@', CACHE = 'aiagents-' + VERSION, PRECACHE = @PRECACHE@;
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(PRECACHE); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf('aiagents-') === 0 && k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
function fromCache(req) { return caches.match(req, {ignoreSearch: true}); }
function store(req, res) {
  if (res && (res.ok || res.type === 'opaque')) { var copy = res.clone(); caches.open(CACHE).then(function (c) { c.put(req, copy); }); }
  return res;
}
function networkFirst(req) {
  var timeout = new Promise(function (resolve) { setTimeout(function () { resolve(null); }, 4000); });
  var net = fetch(req).then(function (res) { return store(req, res); }).catch(function () { return null; });
  return Promise.race([net, timeout]).then(function (res) {
    return res || fromCache(req).then(function (hit) { return hit || net.then(function (late) { return late || Response.error(); }); });
  });
}
function cacheFirst(req) {
  return fromCache(req).then(function (hit) { return hit || fetch(req).then(function (res) { return store(req, res); }); });
}
self.addEventListener('fetch', function (e) {
  var req = e.request; if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.origin === self.location.origin) {
    if (req.mode === 'navigate' || /\.html$/.test(url.pathname) || /\/$/.test(url.pathname)) e.respondWith(networkFirst(req));
    else e.respondWith(cacheFirst(req));
    return;
  }
  if (/^fonts\.(googleapis|gstatic)\.com$/.test(url.hostname) || (url.hostname === 'www.gstatic.com' && url.pathname.indexOf('/firebasejs/') === 0)) {
    e.respondWith(cacheFirst(req));
  }
});
"""


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def write(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8') as f:
        f.write(s)


args = sys.argv[1:]
site_dir, doc_url = None, None
if '--site' in args:
    i = args.index('--site'); args.pop(i)
    site_dir = args.pop(i) if i < len(args) and not args[i].startswith('--') else 'docs'
if '--doc-url' in args:
    i = args.index('--doc-url'); args.pop(i); doc_url = args.pop(i)

css = read(os.path.join(SHARED, 'course.css'))
js = read(os.path.join(SHARED, 'course.js'))
sync_js = read(os.path.join(SHARED, 'firebase-config.js')) + '\n' + read(os.path.join(SHARED, 'sync.js'))
install_js = read(os.path.join(SHARED, 'install.js'))
urls_path = os.path.join(HERE, 'urls.json')
urls = json.loads(read(urls_path)) if os.path.exists(urls_path) else {}
urls.setdefault('weeks', ['#'] * 10)
names = args or [n[:-5] for n in sorted(os.listdir(SRC)) if n.endswith('.html') and not n.startswith('_')]
problems = []


def build_page(name, url_map, site_meta=None):
    page = read(os.path.join(SRC, name + '.html'))
    tag = '<script>window.COURSE_URLS=' + json.dumps(url_map) + ';</script>'
    scripts = tag + '\n<script>\n' + js + '\n</script>\n<script>\n' + sync_js + '\n</script>'
    if site_meta is not None:
        scripts = '<script>window.COURSE_SITE=' + json.dumps(site_meta) + ';</script>\n' + scripts + '\n<script>\n' + install_js + '\n</script>'
    out = page.replace('<!-- @css -->', '<style>\n' + css + '\n</style>')
    out = out.replace('<!-- @js -->', scripts)
    out = out.replace('<!-- @urls -->', tag)
    if '<title>' not in out[:8000]: problems.append(name + ': no <title> in first 8KB')
    for bad in ('<!doctype', '<html', '<head', '<body'):
        if bad in out.lower()[:2000]: problems.append(name + ': contains ' + bad)
    if out.count('<script') != out.count('</script>'): problems.append(name + ': unbalanced <script> tags')
    if '{{' in out: problems.append(name + ': leftover {{ placeholder')
    if 'href="course.css"' in out: problems.append(name + ': links course.css instead of inlining')
    return out


if site_dir:
    site = site_dir if os.path.isabs(site_dir) else os.path.join(HERE, site_dir)
    site_urls = {'hub': 'index.html', 'doc': doc_url or urls.get('doc', '#'), 'playground': 'playground.html',
                 'weeks': ['w%d.html' % n for n in range(1, 11)]}
    if args:
        print('note: the site is always built whole, so the offline list stays complete')
    pages, digest = {}, hashlib.sha1()
    for name in [n[:-5] for n in sorted(os.listdir(SRC)) if n.endswith('.html') and not n.startswith('_')]:
        out = build_page(name, site_urls, {'page': name})
        fname = 'index.html' if name == 'hub' else name + '.html'
        pages[fname] = SKELETON.replace('</head>', SITE_HEAD + '</head>') + out + '</body></html>'
        digest.update(pages[fname].encode('utf-8'))
    for fname in sorted(pages):
        write(os.path.join(site, fname), pages[fname])
        print('site', fname, len(pages[fname]), 'bytes')
    for f in ICON_FILES:
        shutil.copyfile(os.path.join(ASSETS, f), os.path.join(site, f))
        with open(os.path.join(ASSETS, f), 'rb') as fh:
            digest.update(fh.read())
    manifest = json.dumps(MANIFEST, indent=2)
    digest.update(manifest.encode('utf-8'))
    write(os.path.join(site, 'manifest.webmanifest'), manifest)
    version = digest.hexdigest()[:10]
    precache = ['./'] + sorted(pages) + ['manifest.webmanifest'] + ICON_FILES
    write(os.path.join(site, 'sw.js'), SW_TEMPLATE.replace('@VERSION@', version).replace('@PRECACHE@', json.dumps(precache)))
    write(os.path.join(site, '.nojekyll'), '')
    print('site manifest.webmanifest + sw.js (version %s, %d files offline) + %d icons' % (version, len(precache), len(ICON_FILES)))
else:
    for name in names:
        out = build_page(name, urls)
        write(os.path.join(DIST, name + '.html'), out)
        write(os.path.join(DIST, 'preview', name + '.html'), SKELETON + out + '</body></html>')
        print('built', name, len(out), 'bytes')
for p in problems:
    print('WARNING', p)
